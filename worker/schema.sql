CREATE TABLE IF NOT EXISTS jobs (
 id TEXT PRIMARY KEY, uid TEXT NOT NULL, day TEXT NOT NULL,
 units INTEGER NOT NULL, signature TEXT NOT NULL,
 state TEXT NOT NULL DEFAULT 'processing', result TEXT,
 created INTEGER NOT NULL, polled INTEGER NOT NULL DEFAULT 0,
 reserved REAL NOT NULL DEFAULT 0, actual REAL, model TEXT, metadata TEXT, projectId TEXT, nodeId TEXT
);
CREATE INDEX IF NOT EXISTS jobs_day ON jobs(day,uid);

CREATE TABLE IF NOT EXISTS accounts(uid TEXT PRIMARY KEY,email TEXT NOT NULL,name TEXT NOT NULL,status TEXT NOT NULL DEFAULT 'pending',daily_usd REAL NOT NULL DEFAULT 2,created INTEGER NOT NULL,last_seen INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS settings(id INTEGER PRIMARY KEY CHECK(id=1),daily_usd REAL NOT NULL DEFAULT 10,paused INTEGER NOT NULL DEFAULT 0);
INSERT OR IGNORE INTO settings(id) VALUES(1);
CREATE TABLE IF NOT EXISTS audit(id INTEGER PRIMARY KEY AUTOINCREMENT,actor TEXT NOT NULL,target TEXT NOT NULL,action TEXT NOT NULL,created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS assistant_requests(id TEXT PRIMARY KEY,uid TEXT NOT NULL,created INTEGER NOT NULL,result TEXT);
